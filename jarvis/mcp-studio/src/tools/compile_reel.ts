import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CATALOG_PATH = path.resolve(__dirname, "../../../../content-bank/catalog.json");
const REMOTION_DIR = path.resolve(__dirname, "../../../../production/remotion");
const COMPOSITIONS_DIR = path.join(REMOTION_DIR, "src/compositions/reels");

export function registerCompileReel(server: McpServer) {
  server.tool(
    "compile_reel",
    "Write a Remotion composition for a reel. Claude picks clips with visible reasoning in code comments, then renders to MP4.",
    {
      reel_name: z.string().describe("Slug for the reel file, e.g. training-partner-v2"),
      hook_text: z.string().describe("ALL CAPS hook text shown at start of reel"),
      list_items: z.array(z.string()).describe("Numbered list items as ALL CAPS short text (3-6 words)"),
      render: z.boolean().default(false).describe("If true, runs npm run render after writing composition"),
    },
    async ({ reel_name, hook_text, list_items, render }) => {
      const catalog: Array<Record<string, unknown>> = JSON.parse(readFileSync(CATALOG_PATH, "utf-8"));

      const arrivals = catalog.filter((e) => e["shot_type"] === "arrival");
      const training = catalog.filter((e) => e["shot_type"] === "training");
      const atmosphere = catalog.filter((e) => e["shot_type"] === "atmosphere");
      const hero = catalog.filter((e) => e["shot_type"] === "hero");

      if (!arrivals.length && !training.length) {
        return {
          content: [{ type: "text" as const, text: "Catalog is empty. Run generate_asset first to build the content bank." }],
          isError: true,
        };
      }

      const FRAMES = 150;
      const itemCount = list_items.length;
      const totalFrames = FRAMES + itemCount * FRAMES + 90;

      const clipPool = [...training, ...atmosphere];
      const selectedClips = [
        arrivals[0] || training[0],
        ...clipPool.slice(0, itemCount),
        hero[0] || arrivals[0] || training[0],
      ].filter(Boolean);

      const clipEntries = selectedClips.map((c, i) => {
        const reason =
          i === 0
            ? "opening hook — cinematic arrival sets gym world"
            : i === selectedClips.length - 1
            ? "closing hero shot — ends on face for identity anchor"
            : `item ${i} — ${c["shot_type"]} clip`;
        const dur = i === selectedClips.length - 1 ? 90 : FRAMES;
        return `      // ${reason}\n      { entry: catalog.find((e: AssetEntry) => e.id === "${c["id"]}")!, durationInFrames: ${dur} },`;
      }).join("\n");

      const overlayEntries = [
        `      { text: "${hook_text}", startFrame: 10, durationInFrames: ${FRAMES - 10}, position: "top" as const, isHook: true },`,
        ...list_items.map((item, i) => {
          const start = FRAMES + i * FRAMES + 10;
          return `      { text: "${item}", startFrame: ${start}, durationInFrames: ${FRAMES - 20}, position: "center" as const },`;
        }),
        `      { text: "READ DESCRIPTION ⬇️", startFrame: ${totalFrames - 100}, durationInFrames: 90, position: "bottom" as const },`,
      ].join("\n");

      const componentName = reel_name
        .split("-")
        .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
        .join("");

      const composition = `import React from "react";
import { ReelComposition } from "../ReelComposition";
import { catalog, AssetEntry } from "../../lib/catalog";

// REEL: ${hook_text}
// Generated by Jarvis Studio MCP — ${new Date().toISOString().slice(0, 10)}
// Total: ${totalFrames} frames (${(totalFrames / 30).toFixed(1)}s at 30fps)

export const ${componentName}: React.FC = () => (
  <ReelComposition
    clips={[
${clipEntries}
    ]}
    hookText={"${hook_text}"}
    overlayItems={[
${overlayEntries}
    ]}
  />
);
`;

      const outPath = path.join(COMPOSITIONS_DIR, `${reel_name}.tsx`);
      writeFileSync(outPath, composition, "utf-8");

      const renderCmd = `cd "${REMOTION_DIR}" && npm run render -- --composition ${componentName} --output out/${reel_name}.mp4`;

      let renderOutput = "";
      if (render) {
        const { execSync } = await import("child_process");
        renderOutput = execSync(renderCmd, { encoding: "utf-8", timeout: 300_000 });
      }

      return {
        content: [{
          type: "text" as const,
          text: `Composition written to ${outPath}\n\nTo render:\n${renderCmd}\n\n${renderOutput}`,
        }],
      };
    }
  );
}
